type DeepString<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepString<T[K]>;
};
export type TranslationKeys = DeepString<typeof translations['ja']>;

// Both languages must provide the same keys
const _check: TranslationKeys = translations.en;
void _check;

// Replaces {name} placeholders with values
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => (key in vars ? String(vars[key]) : `{${key}}`));
}

